-- Master database for orders, items, shipments and events (generated from master_spec.json).

create table if not exists "stores" (
  "id" text primary key,
  "name" text not null,
  "shopify_domain" text not null unique,
  "currency" text not null default 'USD',
  "timezone" text not null default 'America/Los_Angeles',
  "active" boolean not null default true
);
comment on table "stores" is 'The two Shopify stores. Every row in every other table says which store it belongs to.';

create table if not exists "orders" (
  "id" bigint primary key,
  "store" text not null references "stores" ("id"),
  "name" text not null,
  "customer_id" bigint,
  "customer_name" text,
  "email" text,
  "phone" text,
  "ship_name" text,
  "ship_address1" text,
  "ship_address2" text,
  "ship_city" text,
  "ship_province" text,
  "ship_zip" text,
  "ship_country" text,
  "placed_at" timestamptz not null,
  "shop_updated_at" timestamptz not null,
  "cancelled_at" timestamptz,
  "cancel_reason" text,
  "financial_status" text,
  "fulfillment_status" text,
  "currency" text not null default 'USD',
  "subtotal" numeric(12,2),
  "discounts" numeric(12,2),
  "shipping_charged" numeric(12,2),
  "tax" numeric(12,2),
  "total" numeric(12,2),
  "refunded_amount" numeric(12,2) not null default 0,
  "tags" text[] not null default '{}',
  "note" text,
  "risk_level" text,
  "raw" jsonb,
  "synced_at" timestamptz not null default now(),
  "stage" text not null default 'new',
  "stage_at" timestamptz not null default now(),
  "due_at" timestamptz,
  "late" boolean not null default false,
  "checked_by" text,
  "checked_at" timestamptz,
  "hold_reason" text,
  "hold_by" text,
  "hold_at" timestamptz,
  "dispute" text,
  "open_alerts" int not null default 0,
  "worst_alert" text,
  "closed_at" timestamptz,
  "updated_by" text,
  "updated_at" timestamptz not null default now()
);
comment on table "orders" is 'One row per Shopify order. Left half is Shopify''s copy (sync only); right half is our status, hold and alert summary (our team and jobs only).';

create table if not exists "items" (
  "id" bigint primary key,
  "order_id" bigint not null references "orders" ("id"),
  "store" text not null references "stores" ("id"),
  "sku" text,
  "title" text not null,
  "variant_title" text,
  "product_id" bigint,
  "variant_id" bigint,
  "image_url" text,
  "qty" int not null,
  "current_qty" int not null,
  "refunded_qty" int not null default 0,
  "fulfilled_qty" int not null default 0,
  "open_qty" int not null default 0,
  "price" numeric(12,2),
  "discount" numeric(12,2) not null default 0,
  "route" text,
  "send_qty" int,
  "out_of_stock" boolean not null default false,
  "shelf" text,
  "shelf_qty" int,
  "ppc_route" text,
  "erp_order_no" text,
  "updated_by" text,
  "updated_at" timestamptz not null default now()
);
comment on table "items" is 'One row per order line. Shopify''s quantities (ordered, after edits, refunded, shipped, still open) plus our decision: route, send quantity, out of stock, shelf.';

create table if not exists "shipments" (
  "id" uuid primary key default gen_random_uuid(),
  "order_id" bigint not null references "orders" ("id"),
  "store" text not null references "stores" ("id"),
  "seq" int not null,
  "kind" text not null,
  "items" jsonb not null,
  "step" text not null,
  "step_at" timestamptz not null default now(),
  "step_times" jsonb not null default '{}',
  "responsible" text,
  "responsible_since" timestamptz,
  "due_at" timestamptz,
  "late" boolean not null default false,
  "block_reason" text,
  "ship_to" jsonb,
  "carrier" text,
  "service" text,
  "tracking" text[] not null default '{}',
  "mcf_id" text unique,
  "mcf_account" text,
  "shopify_fulfillment_id" bigint unique,
  "dispatch_file" text,
  "gst_invoice_no" text unique,
  "weight_kg" numeric(6,2),
  "dims_cm" text,
  "cost" numeric(12,2),
  "eta" date,
  "delivered_at" timestamptz,
  "last_scan_at" timestamptz,
  "last_scan_place" text,
  "last_scan_text" text,
  "cities" text[] not null default '{}',
  "return_reason" text,
  "return_outcome" text,
  "linked_id" uuid references "shipments" ("id"),
  "created_by" text,
  "created_at" timestamptz not null default now(),
  "updated_at" timestamptz not null default now(),
  unique ("order_id", "seq")
);
comment on table "shipments" is 'Anything that moves: an MCF parcel, an India parcel, a production job, a return coming back, a replacement going out. Holds the step, who is responsible now, tracking, GST number and costs.';

create table if not exists "events" (
  "id" bigserial primary key,
  "at" timestamptz not null default now(),
  "store" text references "stores" ("id"),
  "order_id" bigint references "orders" ("id"),
  "shipment_id" uuid references "shipments" ("id"),
  "item_id" bigint references "items" ("id"),
  "type" text not null,
  "by" text not null,
  "title" text not null,
  "data" jsonb,
  "external_id" text unique,
  "parent_id" bigint references "events" ("id"),
  "alert_kind" text,
  "severity" text,
  "level" int,
  "owner_team" text,
  "assigned_to" text,
  "reason" text,
  "action" text,
  "due_at" timestamptz,
  "seen_at" timestamptz,
  "escalated_at" timestamptz,
  "closed_at" timestamptz,
  "closed_by" text
);
comment on table "events" is 'Everything that happened, once: Shopify messages, step changes, tracking scans, notes, actions, and alerts with their whole life (seen, answered, escalated, closed). The order page timeline is just these rows.';

create unique index if not exists events_external on "events" ("external_id") where "external_id" is not null;
